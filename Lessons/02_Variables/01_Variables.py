# This program demonstrates the use of variables in Python.

name = "Krishna"    # stores a string
age = 22            # stores an integer
height = 182.0      # stores a float
is_student = True   # stores a boolean

print("Name:", name)
print("Age:", age)
print("Height (cm):", height)
print("Is Student:", is_student)


# Reassigning variables
x = 10
print(x)  # 10

x = 25
print(x)  # 25




# Multiple assignments
a, b, c = 1, 2, 3
print(a, b, c)  # 1 2 3

# Or assigning the same value to multiple variables

x = y = z = 100
print(x, y, z)  # 100 100 100



# Dynamic typing
x = 10         # integer
print(x)  # 10
x = "hello"    # now string
print(x)  # hello
x = 3.14       # now float
print(x)  # 3.14



